-- Correlation chart Rp/Kg vs Yield: per BA/afd/bulan, cost 5 komponen (tanpa Infra & Penyusutan, basis sama dgn pbix) dalam ribu Rp, ton (MAX per bulan-BA-afd)
SELECT DECODE(KODE_BA,'2122','2131',KODE_BA) ba, KODE_AFD afd, TO_CHAR(DATE_TRUNC('month',BULAN),'YYYY-MM') m,
 ROUND(SUM(IFF(GROUP_LEVEL IN ('BIAYA PERAWATAN','BIAYA PEMUPUKAN','BIAYA PANEN','TRANSPORT PANEN','BIAYA UMUM','COST SEWA AMP'),RP_ACTUAL,0))/1000) c5, ROUND(MAX(TON_ACTUAL),1) ton
FROM PRD_DB_PRESENTATION.PRS_COST.ESTATE_COST
WHERE KODE_BA IN ('2121','2124','2131','2122') AND NOT (DECODE(KODE_BA,'2122','2131',KODE_BA)='2131' AND KODE_AFD='B') AND BULAN>='2026-01-01' AND BULAN<'2026-10-01'
GROUP BY 1,2,3 ORDER BY 1,2,3;
